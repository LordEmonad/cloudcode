import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
page.on('pageerror', (e) => console.log('pageerror:', e.message));
await page.goto('http://127.0.0.1:5173/');
await page.waitForFunction(() => window.__game && window.__game.state === 'aim', null, { timeout: 90000 });
await page.evaluate(() => window.__ngd.fling(0, 300));
await page.evaluate(() => window.__ngd.warp('whale', 0.85, 6));
await page.waitForTimeout(1200);
const out = await page.evaluate(() => {
  const g = window.__gameObj;
  const o = g.course.obstacles.find((x) => x.label === 'MEGA WHALE');
  const r = o.body.rotation();
  const q = o.mesh.quaternion;
  const nose = o.mesh.localToWorld(o.mesh.position.clone().set(1, 0, 0)).sub(o.mesh.getWorldPosition(o.mesh.position.clone())).normalize();
  const cam = g.rig.camera;
  const fwd = cam.getWorldDirection(nose.clone());
  const sec = g.course.track.section('pool');
  const f = g.course.track.samples[sec.i0].f;
  return { bodyRot: [r.x, r.y, r.z, r.w].map((v) => +v.toFixed(2)), meshQ: [q.x, q.y, q.z, q.w].map((v) => +v.toFixed(2)), nose: nose.toArray().map((v) => +v.toFixed(2)), camFwd: fwd.toArray().map((v) => +v.toFixed(2)), trackF: f.toArray().map((v) => +v.toFixed(2)), noseDotTrack: +nose.dot(f).toFixed(2), noseDotCam: +nose.dot(fwd).toFixed(2), children: o.mesh.children.length };
});
console.log(JSON.stringify(out));
await page.screenshot({ path: '/tmp/claude-0/-home-user-cloudcode/04b51238-34b1-530f-9cac-e62d57236f8d/scratchpad/whale_probe.png' });
await browser.close();
